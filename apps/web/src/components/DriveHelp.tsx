import { useState } from 'react';
import { Info } from 'lucide-react';
import { t, tj } from '../lib/i18n.ts';
import { Dialog } from './ui.tsx';

/** Кнопка-«i» рядом с подсказкой поля URL медиа: окно о том, как класть в досье картинки и видео с Гугл-диска. */
export function DriveHelpButton() {
  const [open, setOpen] = useState(false);
  return (
    <>
      <button
        type="button"
        title={t('Как использовать ссылки на Гугл-диск')}
        aria-label={t('Как использовать ссылки на Гугл-диск')}
        onClick={(e) => {
          // Кнопка стоит внутри <label>: без preventDefault клик ещё и переводит фокус в поле.
          e.preventDefault();
          setOpen(true);
        }}
        className="inline-flex cursor-pointer items-center align-text-bottom text-mute transition hover:text-mint"
      >
        <Info size={14} />
      </button>
      <Dialog open={open} onOpenChange={setOpen} title={t('Картинки и видео с Гугл-диска')} stacked>
        <div className="space-y-4 text-sm leading-relaxed text-text">
          <p>
            {t('Встроенные медиафайлы ограничены: до 1 МБ на файл и 5 МБ на досье. Большие фото, сканы и видео держите на своём Гугл-диске, а в досье кладите ссылку — сайт покажет картинку или проиграет видео прямо на странице.')}
          </p>
          <ol className="list-decimal space-y-2 pl-5">
            <li>
              {tj('Откройте файл на Гугл-диске и нажмите {share} (или «Открыть доступ»). В разделе «Общий доступ» выберите {anyone} с правом «Читатель». Без этого Диск не отдаст файл сайту.', {
                share: <b>{t('Поделиться')}</b>,
                anyone: <b>{t('Все, у кого есть ссылка')}</b>,
              })}
            </li>
            <li>
              {tj('Нажмите {copy}. Подойдёт любая ссылка Диска на файл:', { copy: <b>{t('Копировать ссылку')}</b> })}
              <span className="mt-1 block font-mono text-xs text-dim">
                https://drive.google.com/file/d/…/view?usp=sharing
                <br />
                https://drive.google.com/open?id=…
              </span>
            </li>
            <li>
              {tj('Вставьте её в поле {field} этой формы. Сайт сам распознает ссылку Диска и покажет переключатель {toggle}: по ссылке не видно, что в файле, поэтому выберите сами.', {
                field: <b>{t('«…или URL изображения»')}</b>,
                toggle: <b>{t('Изображение / Видео')}</b>,
              })}
            </li>
            <li>
              {tj('Заполните подпись, альбом и источник, нажмите {add}. Картинка откроется в просмотре как обычное фото, видео — во встроенном плеере Диска (значок ▶ на плитке).', {
                add: <b>{t('Добавить')}</b>,
              })}
            </li>
          </ol>
          <div className="space-y-1.5 rounded-lg border border-line-soft bg-bg-soft p-3 text-xs text-dim">
            <p><b className="text-text">{t('Что важно знать.')}</b></p>
            <p>{t('Файл остаётся у вас на Диске: сайт хранит только ссылку, в лимит объёма она не входит. Если закрыть доступ или удалить файл, в досье останется пустая плитка.')}</p>
            <p>{t('Картинка показывается через миниатюру Диска шириной до 1600 px; видео проигрывает плеер Google — для него нужны обычные права на Диске и доступ в интернет с вашего компьютера.')}</p>
            <p>{t('Папки Диска и ссылки на Google Фото не подходят — нужна ссылка на конкретный файл.')}</p>
            <p>{t('Доступ «всем, у кого есть ссылка» делает файл доступным любому, кто узнает ссылку. Для сканов документов и другого чувствительного материала лучше встраивать файл в досье или не давать ссылку в общий доступ.')}</p>
            <p>{t('В файл экспорта (.ftx) видео попадает как картинка-кадр: ссылку на плеер экспорт пока не переносит.')}</p>
          </div>
        </div>
      </Dialog>
    </>
  );
}
